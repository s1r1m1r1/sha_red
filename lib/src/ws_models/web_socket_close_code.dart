/// Кастомные статус-коды закрытия WebSocket (диапазон 4000-4999)
/// Согласно спецификации IANA для частного использования.
enum WebSocketCloseCode {
  // --- Секция авторизации (4001-4099) ---

  /// Токен авторизации истек или недействителен.
  tokenExpired(4001, 'Сессия истекла. Пожалуйста, войдите снова.'),

  /// У пользователя нет прав для доступа к этому ресурсу.
  forbidden(4003, 'Доступ запрещен.'),

  // --- Секция сессий (4100-4199) ---

  /// Вход с другого устройства (вытеснение текущей сессии).
  sessionConflict(4100, 'Вход выполнен с другого устройства.'),

  /// Клиент отправляет сообщения слишком часто.
  rateLimitExceeded(4129, 'Слишком много запросов.'),

  // --- Секция логики приложения (4500+) ---

  /// Версия приложения устарела и не поддерживается сервером.
  updateRequired(4200, 'Необходимо обновить приложение.'),

  /// Комната или лобби заполнено (для игр/чатов).
  roomFull(4500, 'Комната заполнена.');

  /// Числовой код для отправки/получения в WebSocket
  final int code;

  /// Сообщение для пользователя или лога
  final String message;

  const WebSocketCloseCode(this.code, this.message);

  /// Метод для поиска enum по полученному коду от сервера
  static WebSocketCloseCode? fromCode(int code) {
    for (var value in WebSocketCloseCode.values) {
      if (value.code == code) return value;
    }
    return null;
  }
}
